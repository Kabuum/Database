-- attribute_class: the possible classes of a classification attribute
CREATE TABLE attribute_prediction.attribute_class (
    class_id     int  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id int  NOT NULL REFERENCES attribute_prediction.attribute (attribute_id),
    name         text NOT NULL,
    category     text,                                 -- optional coarse grouping, e.g. highway / main / minor
    UNIQUE (attribute_id, name),
    UNIQUE (attribute_id, class_id)                    -- target for composite FKs that pin a class to its attribute
);

