-- model_run: one training run predicting one attribute
CREATE TABLE attribute_prediction.model_run (
    run_id             int  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id       int  NOT NULL,
    label_rule_version int  NOT NULL,
    split_id           int  NOT NULL REFERENCES attribute_prediction.split (split_id),
    feature_set_id     int  NOT NULL REFERENCES attribute_prediction.feature_set (feature_set_id),
    architecture       text NOT NULL,                  -- GraphSAGE / MLP / majority
    hyperparameters    jsonb,
    seed               int  NOT NULL,
    code_version       text,                           -- git commit hash
    started_at         timestamp,
    status             attribute_prediction.run_status NOT NULL,
    FOREIGN KEY (attribute_id, label_rule_version)
        REFERENCES attribute_prediction.label_rule (attribute_id, version)
);

CREATE INDEX model_run_attr_idx ON attribute_prediction.model_run (attribute_id);
