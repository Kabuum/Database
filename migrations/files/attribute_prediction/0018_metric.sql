-- metric: evaluation results per run / partition / level
CREATE TABLE attribute_prediction.metric (
    metric_id   int  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      int  NOT NULL REFERENCES attribute_prediction.model_run (run_id) ON DELETE CASCADE,
    partition   attribute_prediction.partition    NOT NULL,
    level       attribute_prediction.metric_level NOT NULL,
    metric_name text NOT NULL,                         -- macro_f1, weighted_f1, precision, recall, f1, mae, rmse
    class_id    int  REFERENCES attribute_prediction.attribute_class (class_id),  -- NULL for averaged metrics
    value       double precision NOT NULL
);

CREATE INDEX metric_run_idx ON attribute_prediction.metric (run_id);
